//!
//! Source : définitions publiques `D3D10_SB_OPCODE_TYPE` / `D3D11_SB_OPCODE_TYPE`
//! (`d3d10tokenizedprogramformat.h`, `d3d11tokenizedprogramformat.h`). Les valeurs numériques sont
//! celles du format de jetons ; les identifiants et noms ci-dessous sont les nôtres.
#![allow(dead_code)]

macro_rules! opcodes {
    ($($id:ident = $v:literal, $name:literal;)*) => {
        $(pub const $id: u32 = $v;)*
        /// Nom d'assembleur (`add`, `dcl_temps`, ...) d'un opcode SM4/SM5.
        pub fn opcode_name(op: u32) -> &'static str {
            match op { $($v => $name,)* _ => "unknown" }
        }
    };
}

